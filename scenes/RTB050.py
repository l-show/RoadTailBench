def main():
    actor_list = []
    client = carla.Client('localhost', 2000)
    client.set_timeout(10.0)

    try:
        world = client.get_world()
        carla_map = world.get_map()
        dt = 0.05

        # ==========================================
        # 1. 环境初始化：帧率同步与天气系统
        # ==========================================
        RTB.enable_synchronous_mode(world, dt=dt)

        # 严格按照截图参数硬编码配置天气环境
        weather = carla.WeatherParameters(
            cloudiness=5.0,
            precipitation=0.0,
            precipitation_deposits=30.0,  # Puddles
            wind_intensity=15.0,
            sun_azimuth_angle=39.0,
            sun_altitude_angle=90.0,
            fog_density=2.0,
            fog_distance=0.75,
            fog_falloff=0.1,
            wetness=30.0,
            scattering_intensity=0.0,  # Scatter
            mie_scattering_scale=0.03,
            rayleigh_scattering_scale=0.05,
            dust_storm=0.0
        )
        world.set_weather(weather)
        print("[场景配置] 天气系统已按照截图参数精确配置完成。")

        # ==========================================
        # 2. 轨迹数据清洗与平滑稠密化 (interval=0.5m)
        # ==========================================
        raw_truck = RTB.parse_string_trajectory(TRAJ_STR_TRUCK)
        raw_ego = RTB.parse_string_trajectory(TRAJ_STR_EGO)
        raw_car3 = RTB.parse_string_trajectory(TRAJ_STR_CAR3)

        traj_truck = RTB.interpolate_trajectory(raw_truck, interval=0.5)
        traj_ego = RTB.interpolate_trajectory(raw_ego, interval=0.5)
        traj_car3 = RTB.interpolate_trajectory(raw_car3, interval=0.5)

        # 绘制所有车辆的预设路径 (灰色展示)
        RTB.draw_preset_trajectory(world, traj_truck, color=carla.Color(150, 150, 150))
        RTB.draw_preset_trajectory(world, traj_ego, color=carla.Color(150, 150, 150))
        RTB.draw_preset_trajectory(world, traj_car3, color=carla.Color(150, 150, 150))

        # ==========================================
        # 3. 车辆实体安全生成
        # ==========================================
        # 车辆1: 消防卡车 (必须使用较大的 z_offset=1.5 防止卡地)
        truck = RTB.spawn_vehicle(world, 'vehicle.carlamotors.firetruck',
                                  x=raw_truck[0][0], y=raw_truck[0][1], yaw=raw_truck[0][2],
                                  role_name='npc_truck', z_offset=1.5)

        # 车辆2: EGO 小轿车
        ego = RTB.spawn_vehicle(world, 'vehicle.audi.tt',
                                x=raw_ego[0][0], y=raw_ego[0][1], yaw=raw_ego[0][2],
                                role_name='ego', z_offset=0.5)

        # 车辆3: NPC 小轿车
        car3 = RTB.spawn_vehicle(world, 'vehicle.chevrolet.impala',
                                 x=raw_car3[0][0], y=raw_car3[0][1], yaw=raw_car3[0][2],
                                 role_name='npc_car', z_offset=0.5)

        # 保护性存活判断并将成功生成的车加入销毁列表
        for v in [truck, ego, car3]:
            if v: actor_list.append(v)

        # ==========================================
        # 4. 车辆灯光管理器设置
        # ==========================================
        if ego:
            ego_lights = RTB.VehicleLightManager(ego)
            ego_lights.set_static_lights(low_beam=False, high_beam=True)  # EGO要求行车灯、远光灯

        if car3:
            car3_lights = RTB.VehicleLightManager(car3)
            car3_lights.set_static_lights(low_beam=True, high_beam=False)  # CAR3要求行车灯、近光灯

        # ==========================================
        # 5. PID 独立控制器挂载与状态机编排
        # ==========================================
        # 必须为每一辆车实例化独立的横纵向 PID 控制器！
        pid_lon_truck = RTB.PIDLongitudinalController(preset='truck', dt=dt)
        pid_lat_truck = RTB.PIDLateralController(preset='truck', dt=dt)

        pid_lon_ego = RTB.PIDLongitudinalController(preset='default_car', dt=dt)
        pid_lat_ego = RTB.PIDLateralController(preset='default_car', dt=dt)

        pid_lon_car3 = RTB.PIDLongitudinalController(preset='default_car', dt=dt)
        pid_lat_car3 = RTB.PIDLateralController(preset='default_car', dt=dt)

        # 剧本状态机编排：
        # Truck 和 Car3 保持恒定速度即可
        sm_truck = RTB.MultiStageBehaviorMachine(initial_speed=30.0)
        sm_car3 = RTB.MultiStageBehaviorMachine(initial_speed=70.0)

        # Ego 复杂剧本：初始60 -> x>50减速到20 -> 等待2秒 -> 恢复60
        sm_ego = RTB.MultiStageBehaviorMachine(initial_speed=60.0)
        sm_ego.add_stage(trigger_type='x_greater', trigger_val=50.0, target_speed=20.0, accel=20.0)  # 刹车减速阶段
        sm_ego.add_stage(trigger_type='time', trigger_val=2.0, target_speed=60.0, accel=15.0)  # 等待2s后提速阶段

        # ==========================================
        # 6. 预热与初始物理动量注入 (防起步打滑画龙)
        # ==========================================
        if truck: RTB.set_vehicle_initial_speed(truck, 30.0, raw_truck[0][2])
        if ego: RTB.set_vehicle_initial_speed(ego, 60.0, raw_ego[0][2])
        if car3: RTB.set_vehicle_initial_speed(car3, 70.0, raw_car3[0][2])

        # ==========================================
        # 7. 仿真主循环 (帧率同步与出界守护)
        # ==========================================
        sim_time = 0.0
        idx_truck, idx_ego, idx_car3 = 0, 0, 0  # 独立维护每辆车的循迹滑窗索引

        print("\n[开始仿真] 进入实时渲染主循环...")
        while True:
            # 记录本帧开始的时间，用于补齐时钟
            start_time = time.time()
            world.tick()
            sim_time += dt

            # --- 卡车控制逻辑 ---
            if truck and truck.is_alive:
                speed_truck = sm_truck.tick(truck.get_location(), sim_time, dt)
                wp_truck, idx_truck = RTB.get_target_waypoint(truck.get_location(), traj_truck, idx_truck, speed_truck)
                RTB.apply_pid_control(truck, pid_lon_truck, pid_lat_truck, speed_truck, wp_truck)
                RTB.check_vehicle_out_of_bounds(truck, carla_map, auto_destroy=True)

            # --- EGO 控制与预瞄可视化 ---
            if ego and ego.is_alive:
                # 状态机会自动判断 X=50 的条件并返回平滑加减速
                speed_ego = sm_ego.tick(ego.get_location(), sim_time, dt)
                wp_ego, idx_ego = RTB.get_target_waypoint(ego.get_location(), traj_ego, idx_ego, speed_ego)
                RTB.apply_pid_control(ego, pid_lon_ego, pid_lat_ego, speed_ego, wp_ego)

                # 画出动态预瞄点和牵引线 (绿色)
                RTB.draw_lookahead_point(world, ego.get_location(), wp_ego, color=carla.Color(0, 255, 0))

                # 出界自动触发 destroy
                RTB.check_vehicle_out_of_bounds(ego, carla_map, auto_destroy=True)

            # --- Car3 控制逻辑 ---
            if car3 and car3.is_alive:
                speed_car3 = sm_car3.tick(car3.get_location(), sim_time, dt)
                wp_car3, idx_car3 = RTB.get_target_waypoint(car3.get_location(), traj_car3, idx_car3, speed_car3)
                RTB.apply_pid_control(car3, pid_lon_car3, pid_lat_car3, speed_car3, wp_car3)
                RTB.check_vehicle_out_of_bounds(car3, carla_map, auto_destroy=True)

            # ---------------- 硬件时钟补齐 (强制 1X 真实时间流逝) ----------------
            compute_time = time.time() - start_time
            if compute_time < dt:
                time.sleep(dt - compute_time)

    except KeyboardInterrupt:
        print("\n[场景中断] 用户手动中断了仿真。")
    finally:
        # 恢复异步模式并一键安全清理场景实体，防止报错
        RTB.disable_synchronous_mode(world)
        RTB.cleanup_actors(client, actor_list)
        print("[场景结束] 资源已安全回收。")


if __name__ == '__main__':
    main()