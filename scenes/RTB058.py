        if mustang: RTB.set_vehicle_initial_speed(mustang, target_speed_kmh=30.0, yaw_deg=myaw2)
        if ego: RTB.set_vehicle_initial_speed(ego, target_speed_kmh=60.0, yaw_deg=eyaw)

